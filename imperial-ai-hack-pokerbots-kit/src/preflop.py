def _spec(i):
    a, b = divmod(i, 13)
    if a == b:
        return True
    if a > b:                    # suited: aces, broadways, connectors and one-gappers
        return a == 12 or b >= 8 or (a - b <= 2 and b >= 2)
    return False


def _impl(i):
    a, b = divmod(i, 13)
    if a == b:
        return 0.14 if a <= 7 else (0.08 if a <= 9 else 0.0)
    if a > b:
        return 0.05 if _spec(i) else 0.02
    return 0.0


