class _Prof(object):
    """Read-only view of one seat's shared profile, expressed as the estimates the policy needs."""
    __slots__ = ("p", "ml", "ma", "mt")

    def __init__(self, p):
        p = p if isinstance(p, dict) else {}
        self.p = p
        try:
            h = float(p.get("hands", 0) or 0)
            w = h / (h + 20.0) if X_STATS else 0.0
            self.ml = 1.0 + w * (float(p.get("vpip", 0.25)) / 0.25 - 1.0)
            self.ma = 1.0 + w * (float(p.get("pfr", 0.15)) / 0.15 - 1.0)
            self.mt = 1.0 + w * (float(p.get("three_bet", 0.06)) / 0.06 - 1.0)
        except (TypeError, ValueError):
            self.ml = self.ma = self.mt = 1.0
        for k in ("ml", "ma", "mt"):
            v = getattr(self, k)
            setattr(self, k, 0.05 if v < 0.05 else (6.0 if v > 6.0 else v))

    def _opt(self, name):
        v = self.p.get(name)
        return float(v) if isinstance(v, (int, float)) and X_STATS else None

    def probs(self, key):
        f, c, r = _PRI[key]
        c *= self.ml
        r *= self.mt if key not in ("f3", "f4") else self.ma
        direct = self._opt("fold_to_3bet") if key == "f3" else (
            self._opt("fold_to_steal") if key in ("bbl", "bbe", "sb") else None)
        cont = c + r
        if direct is not None:
            want = 1.0 - min(0.99, max(0.0, direct))
            c, r = c * want / cont, r * want / cont
            cont = want
        if cont > 0.97:
            c, r = c * 0.97 / cont, r * 0.97 / cont
            cont = 0.97
        return 1.0 - cont, c, r

    def fold(self, key):
        return self.probs(key)[0]

    def open_w(self, b):
        return min(0.95, _PRFI[b] * self.ma)

    def threebet_w(self, key):
        return self.probs(key)[2]

    def call_w(self, key):
        return self.probs(key)[1]

    def shove_first_w(self):
        return max(0.012, min(0.6, 0.02 * self.ma * self.ma))

    def shove_over_w(self):
        return max(0.012, min(0.6, 0.02 * self.mt * self.mt))

    def ai_q(self):
        d = self._opt("call_allin")
        if d is not None:
            return min(0.9, max(0.004, d))
        return min(0.35, max(0.004, _AI_Q0 * self.ml))

    def call_jam(self):
        d = self._opt("call_jam")
        return None if d is None else min(0.97, max(0.03, d))

    def opt_raise(self):
        return min(0.9, 0.15 * self.ma)

    def med_size(self):
        return 0.0

    def loosen(self, x, which):
        return x


