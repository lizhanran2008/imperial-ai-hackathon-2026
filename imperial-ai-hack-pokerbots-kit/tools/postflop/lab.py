"""Shared plumbing for the postflop lab: paths, loading and bundling."""
import hashlib
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(KIT, "src")
OUT = os.path.join(HERE, "out")
STRATEGIES = os.path.join(HERE, "strategies")
CONTROL = os.path.join(STRATEGIES, "starter.py")
CHAMPION = os.path.join(SRC, "postflop.py")
# The control rule ignores the street, so it also serves as the frozen preflop.
BASELINE_PREFLOP = CONTROL
OPPONENT_MODEL = os.path.join(SRC, "opponents.py")
# The integration task (Issue #7) records a 200 KB limit on the uploaded bot.py.
# Not stated in the kit README; treat it as the budget for embedded tables.
SIZE_LIMIT = 200000

for _p in (KIT, SRC, HERE):
    if _p not in sys.path:
        sys.path.insert(0, _p)

_cache = {}


def resolve(path):
    """Find a file given relative to the current folder or to the kit."""
    for cand in (os.path.abspath(path), os.path.join(KIT, path)):
        if os.path.isfile(cand):
            return cand
    sys.exit("Can't find file: %s" % path)


def label(path):
    """Short display name: the file name, or folder/file for a champion."""
    path = os.path.abspath(path)
    if path == CHAMPION:
        return "champion"
    name = os.path.splitext(os.path.basename(path))[0]
    if os.path.dirname(path) != STRATEGIES and not path.startswith(KIT + os.sep):
        # A file from another checkout: say which, so two can be told apart.
        return "%s@%s" % (name, hashlib.md5(path.encode()).hexdigest()[:4])
    return name


def load(path):
    """Import a Python file as its own module (cached per process)."""
    path = os.path.abspath(path)
    if path not in _cache:
        name = "lab_%s_%s" % (os.path.splitext(os.path.basename(path))[0],
                              hashlib.md5(path.encode()).hexdigest()[:8])
        spec = importlib.util.spec_from_file_location(name, path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _cache[path] = module
    return _cache[path]


def opponent_model():
    """The team's opponent model module if it exists yet, else None."""
    return load(OPPONENT_MODEL) if os.path.isfile(OPPONENT_MODEL) else None


def agent_class(path, preflop_path=BASELINE_PREFLOP):
    """An Agent class for `path`: a full bot file's own Agent, or a postflop
    strategy file wrapped with the given preflop."""
    module = load(path)
    if hasattr(module, "Agent"):
        return module.Agent
    if not hasattr(module, "decide"):
        sys.exit("%s defines neither Agent nor decide(state, profiles)." % path)
    from agent_wrapper import build_agent
    return build_agent(load(preflop_path), module, opponent_model())


BUNDLE = '''"""Generated by tools/postflop/make_bot.py. Do not edit.

postflop: {postflop}
preflop:  {preflop}
"""
import sys
import types

_SOURCES = {sources}


def _module(name):
    module = types.ModuleType(name)
    sys.modules[name] = module
    exec(compile(_SOURCES[name], name + ".py", "exec"), module.__dict__)
    return module


for _name in {order}:
    _module(_name)

Agent = sys.modules["agent_wrapper"].build_agent(
    sys.modules["preflop"], sys.modules["postflop"], sys.modules.get("opponents"))
'''


def bundle(postflop_path, preflop_path=BASELINE_PREFLOP, out_path=None):
    """Write one standalone bot file from a postflop strategy and a preflop.

    Each source file is embedded as text and loaded as a module of its own, so
    `import handeval` inside a strategy keeps working and names cannot clash.
    """
    parts = [("handeval", os.path.join(SRC, "handeval.py"))]
    if os.path.isfile(OPPONENT_MODEL):
        parts.append(("opponents", OPPONENT_MODEL))
    parts += [("preflop", preflop_path), ("postflop", postflop_path),
              ("agent_wrapper", os.path.join(HERE, "agent_wrapper.py"))]
    sources = {}
    for name, path in parts:
        with open(path, encoding="utf-8") as f:
            sources[name] = f.read()
    body = "{\n" + "".join("    %r: %r,\n" % (n, sources[n]) for n, _ in parts) + "}"
    text = BUNDLE.format(postflop=os.path.relpath(postflop_path, KIT),
                         preflop=os.path.relpath(preflop_path, KIT),
                         sources=body, order=repr([n for n, _ in parts]))
    if out_path is None:
        os.makedirs(OUT, exist_ok=True)
        out_path = os.path.join(OUT, label(postflop_path) + ".py")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    size = os.path.getsize(out_path)
    if size > SIZE_LIMIT:
        print("WARNING: %s is %d bytes; Issue #7 records a %d-byte limit on the uploaded file."
              % (os.path.relpath(out_path), size, SIZE_LIMIT), file=sys.stderr)
    return out_path
